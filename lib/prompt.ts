export function buildUserPrompt(input: ReportInput): string {
  const questions = getQuestions(input.childAgeBand, input.hagwonStatus);
  const answerLines = questions.map((q) => {
    const idx = input.answers[q.id];
    const opt = idx !== undefined ? q.options[idx] : undefined;
    // 선택지 안에 큰따옴표가 들어 있어 「」로 감싼다 (따옴표 중첩 방지)
    return opt ? `- ${q.text} → 「${opt.label}」` : null;
  }).filter(Boolean);

  const name = input.childName?.trim();
  const ageLabel = input.childAgeBand ? AGE_BAND_LABEL[input.childAgeBand] : undefined;
  const hagwonLabel = HAGWON_STATUS_OPTIONS.find((o) => o.id === input.hagwonStatus)?.label;
  const insights = pickReinterpretationInsights(input.scores, name || '우리 아이', 2);

  return [
    '다음 진단 결과로 아이 학습 성향 리포트를 작성해 줘.',
    '',
    name ? `[아이 이름] ${name} — 리포트에서 이 이름으로 부른다.` : '[아이 이름] 미입력 — "우리 아이"로 부른다.',
    ageLabel
      ? `[아이 연령대] ${ageLabel} — 이 시기 발달 단계를 반드시 해석에 반영한다.`
      : '[아이 연령대] 미입력 — 특정 연령대를 가정하지 말고 일반적인 톤으로 쓴다.',
    hagwonLabel
      ? `[학원·과외 여부] ${hagwonLabel} — "학원을 고른다면" 섹션 톤에 반영한다.`
      : '[학원·과외 여부] 미입력 — 재평가/첫 선택 어느 쪽으로도 단정하지 말고 일반적인 톤으로 쓴다.',
    '',
    `[성향 요약] ${input.scores.headline}`,
    '',
    '[채점 결과]',
    describeScores(input.scores),
    '',
    '[설문 응답 (부모가 고른 아이의 실제 모습)]',
    ...answerLines,
    '',
    '[재해석 후보] ("어쩌면 의외의 모습"에 최소 1개 반드시 포함 — 위 지침 참고)',
    ...insights.map((s) => `- ${s}`),
  ].join('\n');
}
